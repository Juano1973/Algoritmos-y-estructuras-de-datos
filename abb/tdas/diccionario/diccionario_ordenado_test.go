func TestABBVolumenIteradorCorte(t *testing.T) {
	t.Log("Prueba de volumen de iterador interno, para validar que siempre que se indique que se corte" +
		" la iteración con la función visitar, se corte")

	dic := TDADiccionario.CrearABB[int, int](cmpint)

	/* Inserta 'n' parejas en el hash */
	for i := 0; i < 10000; i++ {
		dic.Guardar(i, i)
	}

	seguirEjecutando := true
	siguioEjecutandoCuandoNoDebia := false

	dic.Iterar(func(c int, v int) bool {
		if !seguirEjecutando {
			siguioEjecutandoCuandoNoDebia = true
			return false
		}
		if c%100 == 0 {
			seguirEjecutando = false
			return false
		}
		return true
	})

	require.False(t, seguirEjecutando, "Se tendría que haber encontrado un elemento que genere el corte")
	require.False(t, siguioEjecutandoCuandoNoDebia,
		"No debería haber seguido ejecutando si encontramos un elemento que hizo que la iteración corte")
}

func cmpMinMay(a, b string) int {
	numb, _ := strconv.Atoi(b)
	numa, _ := strconv.Atoi(a)
	return numb - numa
}
func TestNoDistingueMayMin(t *testing.T) {
	abb := TDADiccionario.CrearABB[string, string](cmpMinMay)

	abb.Guardar("HOLA", "mundo")

	require.Equal(t, "mundo", abb.Obtener("hola"))
	require.True(t, abb.Pertenece("hola"))
}

