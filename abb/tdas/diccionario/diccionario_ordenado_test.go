func cmp(a, b string) int {
	primero := TDADiccionario.ClaveHaseada(a, 1000)
	segundo := TDADiccionario.ClaveHaseada(b, 1000)
	return int(segundo - primero)
}

func cmpint(a, b int) int {
	return b - a
}

